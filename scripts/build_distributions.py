GENERATED = (
    "<!-- Generated by scripts/build_distributions.py from "
    "maxey0_ss/distribution/registry.py. Edits here are overwritten. -->"
)


def _header(target: reg.Target) -> list[str]:
    status = {
        "shipped": "Installs from this repository.",
        "external": (
            "The artifact here is complete. Listing it is a platform action "
            "this repository cannot perform, and does not claim."
        ),
    }[target.status]
    lines = [
        GENERATED,
        "",
        f"# {target.title}",
        "",
        reg.ONE_LINE,
        "",
        f"**{status}**",
        "",
        "## Install",
        "",
        "```",
        target.install,
        "```",
        "",
    ]
    if target.optional_dependency:
        lines += [
            f"The `{target.optional_dependency}` package is an *optional* "
            f"dependency and is never vendored. The adapter imports it at the "
            f"moment it is used, so a build that does not use this harness does "
            f"not import it.",
            "",
        ]
    if target.notes:
        lines += [target.notes, ""]
    return lines


def _surface_table() -> list[str]:
    from maxey0_ss.mcp_surface import build_surface

    surface = build_surface()
    lines = [
        f"## The {len(surface.tools)} tools",
        "",
        "| tool | capability |",
        "|---|---|",
    ]
    for tool in surface.tools:
        lines.append(f"| `{tool.name}` | {tool.capability or 'public'} |")
    lines.append("")
    return lines


