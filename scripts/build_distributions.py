def distribution_matrix(_: reg.Target | None = None) -> str:
    rows = [
        GENERATED, "",
        f"# {reg.PRODUCT} distribution matrix", "",
        f"Version `{__version__}` · MCP `{reg.MCP_PROTOCOL}`", "",
        reg.ONE_LINE, "",
        "| target | platform | kind | status | install |",
        "|---|---|---|---|---|",
    ]
    for t in reg.TARGETS:
        rows.append(
            f"| [`{t.id}`]({_dir_for(t)}/) | {t.platform} | {t.kind} | "
            f"{t.status} | `{t.install.splitlines()[0]}` |"
        )
    rows += [
        "",
        "## What the two statuses mean",
        "",
        "**shipped** — the artifact in this repository is the thing that "
        "installs. Run the command and it works.",
        "",
        "**external** — the artifact is complete and correct, and publication "
        "is a platform action this repository cannot perform: a marketplace "
        "review, an app submission. The manifest is real; the listing is not "
        "ours to claim, so it is not claimed.",
        "",
        "There is no third status. A target with no artifact does not appear "
        "here.",
        "",
        "## One declaration",
        "",
        "Every file under `distributions/` is generated by "
        "`scripts/build_distributions.py` from "
        "`maxey0_ss/distribution/registry.py`, and packaging refuses to run if "
        "they have drifted. A plugin id that disagrees with the package name "
        "that disagrees with the MCP server name does not fail a test — it "
        "fails for a user, once, at install, with no diagnostic.",
        "",
    ]
    return "\n".join(rows)


def _dir_for(target: reg.Target) -> str:
    return target.generates[0].split("distributions/")[1].rsplit("/", 1)[0]


BUILDERS = {
    "README.md": readme,
    "requirements.txt": harness_requirements,
    "mcp.json": mcp_json,
    "connector.json": connector_json,
    "app.json": chatgpt_app_json,
    "openai-connector.json": openai_connector_json,
    "config.toml": codex_config_toml,
    "AGENTS.md": codex_agents_md,
    "agent-card.json": a2a_agent_card,
}


def wanted() -> dict[Path, str]:
    """Every generated file and its exact content."""
    out: dict[Path, str] = {ROOT / "distributions" / "DISTRIBUTION_MATRIX.md": distribution_matrix()}
    for target in reg.TARGETS:
        for rel in target.generates:
            name = rel.rsplit("/", 1)[-1]
            builder = BUILDERS.get(name)
            if builder is None:
                raise SystemExit(f"no builder for {name!r} (target {target.id})")
            out[ROOT / rel] = builder(target)
    return out


def missing_artifacts() -> list[str]:
    """Every declared artifact that is not on disk.

    A row in the registry is a promise that a file exists and works. This is
    the half of that promise a script can check.
    """
    problems = []
    for target in reg.TARGETS:
        for rel in target.artifacts:
            if not (ROOT / rel).exists():
                problems.append(f"{target.id}: declared artifact missing: {rel}")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify, write nothing")
    args = ap.parse_args(argv)

    problems = missing_artifacts()
    files = wanted()

    if args.check:
        drift = [
            str(path.relative_to(ROOT).as_posix())
            for path, text in files.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        existing = {
            p.relative_to(ROOT).as_posix()
            for p in OUT.rglob("*") if p.is_file()
        }
        orphans = sorted(existing - {p.relative_to(ROOT).as_posix() for p in files})
        for problem in problems:
            print(f"  {problem}")
        for d in sorted(drift):
            print(f"  drifted: {d}")
        for o in orphans:
            print(f"  orphan:  {o}")
        if problems or drift or orphans:
            print("\nrun: python scripts/build_distributions.py")
            return 1
        print(f"distributions: {len(files)} files match the registry, "
              f"{len(reg.TARGETS)} targets, every artifact present")
        return 0

    if problems:
        for problem in problems:
            print(f"  [FAIL] {problem}")
        return 1

    import shutil

    if OUT.exists():
        shutil.rmtree(OUT)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files across {len(reg.TARGETS)} distribution targets")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
