"""Generate every distribution manifest from the one registry.

`distributions/` was nineteen files at 0.2.0 — eleven READMEs, four one-line
requirements files, two small JSON — describing what each distribution would
contain. This writes the manifests that actually install.

The reason it is generated rather than written is the reason `plugins/` is:
a plugin id that disagrees with the npm name that disagrees with the MCP server
name does not fail a test, it fails for a user, once, at install, with no
diagnostic. There is one declaration, in `maxey0_ss/distribution/registry.py`,
and everything else is derived from it.

    python scripts/build_distributions.py
    python scripts/build_distributions.py --check   # verify, write nothing

`--check` is invoked by `build_package.py` before anything is zipped, exactly as
`build_planes.py --check` is.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from maxey0_ss import __version__  # noqa: E402
from maxey0_ss.distribution import registry as reg  # noqa: E402

OUT = ROOT / "distributions"


# ---------------------------------------------------------------------------
# shared prose
