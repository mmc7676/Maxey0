def readme(target: reg.Target) -> str:
    lines = _header(target)
    if target.kind in {"server", "connector", "app"}:
        lines += _surface_table()
    if target.artifacts:
        lines += ["## What this is", "", *(f"- `{a}`" for a in target.artifacts), ""]
    lines += [
        "## Identity",
        "",
        f"- product `{reg.PRODUCT}`",
        f"- MCP namespace `{reg.MCP_NAMESPACE}` — every tool and resource",
        f"- distribution id `{reg.DISTRIBUTION_ID}`",
        f"- version `{__version__}`",
        f"- protocol `{reg.MCP_PROTOCOL}`",
        "",
        f"See [the distribution matrix](../{'../' if '/' in target.generates[0].split('distributions/')[1].rsplit('/',1)[0] else ''}DISTRIBUTION_MATRIX.md).",
        "",
    ]
    return "\n".join(lines)


def harness_requirements(target: reg.Target) -> str:
    return (
        f"# Generated by scripts/build_distributions.py. Do not edit.\n"
        f"# Optional dependency for the {target.title} adapter.\n"
        f"# Never vendored and never imported unless the adapter is used: the\n"
        f"# adapter defers the import to the moment it is needed, so a build\n"
        f"# that does not use this harness does not carry it.\n"
        f"{target.optional_dependency}\n"
    )


def mcp_json(target: reg.Target) -> str:
    """A `.mcp.json` fragment naming this server."""
    if target.id == "mcp-stdio":
        server = {
            "command": "python",
            "args": ["-m", f"{reg.PYTHON_PACKAGE}.mcp_stdio_server"],
            "env": {"PYTHONUNBUFFERED": "1"},
        }
    else:
        server = {"type": "http", "url": reg.REMOTE_MCP_URL}
    return json.dumps({"mcpServers": {reg.MCP_NAMESPACE: server}}, indent=2) + "\n"


def connector_json(target: reg.Target) -> str:
    """A remote MCP connector descriptor."""
    return json.dumps(
        {
            "name": reg.MCP_NAMESPACE,
            "title": target.title,
            "description": reg.ONE_LINE,
            "version": __version__,
            "transport": {
                "type": "streamable-http",
                "url": reg.REMOTE_MCP_URL,
                "protocolVersion": reg.MCP_PROTOCOL,
            },
            "authentication": {
                "type": "bearer",
                "required": True,
                "note": (
                    "The edge forwards Authorization verbatim and terminates it "
                    "at the origin. The live origin rejects unauthenticated "
                    "tools/call with a role-'public' permission error; "
                    "maxey0-ss.auth.manifest reports admin_open only if "
                    "MAXEY0_AUTH_MODE=disabled without MAXEY0_PUBLIC=1."
                ),
            },
            "homepage": reg.HOMEPAGE,
            "license": reg.LICENSE,
            "publisher": reg.AUTHOR,
        },
        indent=2,
    ) + "\n"


