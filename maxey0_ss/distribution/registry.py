@dataclass(frozen=True)
class Target:
    """One installable thing, and what a user does to get it."""

    #: Stable identifier. Directory name under `distributions/`.
    id: str
    #: What a human calls it.
    title: str
    #: Which vendor's surface this installs into.
    platform: str
    #: "plugin" | "connector" | "app" | "skills" | "harness" | "sdk" | "server"
    kind: str
    status: str
    #: What the user runs or does.
    install: str
    #: Repo-relative paths that make up the artifact. Every one must exist.
    artifacts: tuple[str, ...] = ()
    #: Generated file -> content builder name in `builders`.
    generates: tuple[str, ...] = ()
    #: Optional python dependency, never vendored.
    optional_dependency: str = ""
    notes: str = ""
    extra: dict[str, Any] = field(default_factory=dict)


