#: The deployed remote surface.
#:
#: `mcp.maxey0.com` is the production endpoint: a Cloudflare Worker edge
#: attached to the `maxey0.com` zone as a Custom Domain (see
#: `workers/mcp-edge/wrangler.jsonc`), fronting a Python origin over a
#: Cloudflare Tunnel. It resolves, and the edge serves the full 2026-07-28
