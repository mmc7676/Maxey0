def public_manifest() -> dict[str, Any]:
    """What `maxey0-ss.distribution` reports. Derived, never written down."""
    return {
        "product": PRODUCT,
        "version": __version__,
        "mcp_protocol": MCP_PROTOCOL,
        "planes": ["context", "execution", "engineering-observation"],
        "protocols": ["MCP " + MCP_PROTOCOL, "A2A"],
        "scw": "enforceable-address-space",
        "targets": [
            {
                "id": t.id,
                "title": t.title,
                "platform": t.platform,
                "kind": t.kind,
                "status": t.status,
                "install": t.install,
                "optional_dependency": t.optional_dependency or None,
            }
            for t in TARGETS
        ],
        "platforms": sorted(BY_PLATFORM),
        "harnesses": [t.id for t in HARNESSES],
        "remote_mcp": REMOTE_MCP_URL,
    }
