"""Every way this product is installed, declared once.

`distributions/` held nineteen files at 0.2.0: eleven READMEs, four one-line
requirements files, two small JSON, two with content. A distribution matrix
whose rows are READMEs describing what a distribution would contain is a label
for a distribution matrix.

The lesson this repository has already learned three times — hand-maintained
exclusion lists, version literals in ten files, plugin trees generated by a
script nothing ran — applies here with more force, because a distribution
manifest is read by somebody else's installer. A plugin id that disagrees with
the npm name that disagrees with the MCP server name does not fail a test; it
fails for a user, once, at install, with no diagnostic.

So this module is the only place a target is described, and
`scripts/build_distributions.py` writes every manifest from it. Adding a
distribution means adding a row here. Editing a generated manifest by hand is
undone on the next build, exactly as it is under `plugins/`.

**Two statuses, and the difference is not cosmetic.**

``shipped``  the artifact in this repository is the thing that installs. A
             reader can run the command in ``install`` and have it working.
``external`` the artifact is complete and correct, and publication is a
             platform action this repository cannot perform — a marketplace
             review, an app submission. The manifest is real; the listing is
             not ours to claim.

There is no third status for "planned". A target with no artifact does not get
a row, it goes in ROADMAP.md with no implementation hints. A row here is a
promise that a file exists and works.
"""
