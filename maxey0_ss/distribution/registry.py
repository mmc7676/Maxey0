def _plane_plugin(plane: str, title: str, summary: str) -> Target:
    """One of the four plugins the marketplace ships beside the full stack.

    The marketplace offered five installable plugins while this registry
    declared one, so `DISTRIBUTION_MATRIX.md` showed a reader a single Claude
    Code plugin and `/plugin marketplace add` offered five. A registry whose
    docstring says it is "the only place a target is described" has to actually
    be that, or it is a fourth list.
    """
    plugin = f"maxey0-{plane}"
    return Target(
        id=f"claude-code-{plane}",
        title=title,
        platform="claude-code",
        kind="plugin",
        status="shipped",
        install=(
            "/plugin marketplace add mmc7676/Maxey0\n"
            f"/plugin install {plugin}@maxey0"
        ),
        artifacts=(f"plugins/{plugin}/.claude-plugin/plugin.json",),
        generates=(f"distributions/claude-code-{plane}/README.md",),
        notes=summary,
    )


